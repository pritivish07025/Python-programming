#program demonstrating working with string

str='hello python'
print(str)  # it is print the whole value
print(str[0])  #it is print the first value
print(str[2:5]) #it is print from the 3rd to 5th
print(str[2:])  #print string starting from 3rd
print(str*2)    #print string two times
print(str+"programming")  #print concatinates string